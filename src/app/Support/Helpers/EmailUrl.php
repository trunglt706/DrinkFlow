<?php

declare(strict_types=1);

namespace App\Support\Helpers;

/**
 * Links printed in email templates.
 *
 * Blade's `{{ $url }}` turns the `&` between query parameters into `&amp;`. That is valid HTML, but mail
 * clients that show or copy the raw source (plain-text views, forwarded messages, the `log` mailer) then
 * hand out `?expires=…&amp;signature=…`, where the signature arrives as an `amp;signature` parameter and
 * the signed link answers 403.
 */
class EmailUrl
{
    /**
     * HTML-safe form of a URL that keeps the query separators as a literal `&`.
     *
     * Everything else is escaped as `e()` does (quotes, `<`, `>`), so the result is safe in an attribute
     * and in text. A literal `&` followed by a parameter name is not decoded by HTML parsers in an
     * attribute (it is followed by `=`), and the app's signed links only use `expires` and `signature`,
     * which are not legacy entity names, so the text form is kept as is too.
     *
     * @param string $url Absolute URL generated by the application.
     * @return string Escaped URL, to print with `{!! !!}`.
     */
    public static function html(string $url): string
    {
        return str_replace('&amp;', '&', e($url));
    }
}
